LiquidEventSimple mapToLiquidEventSimple(domain.LiquidEventComplete liquidEventComplete) {
    return LiquidEventSimple(
        userId: liquidEventComplete.userId!,
        date: liquidEventComplete.eventDate!,
        // ingredients: mapToFoodInEventList(foodEventComplete.foodInfo!),
        drinks: mapToLiquidInEventList(liquidEventComplete.foodInfo!),
    );
}

List<LiquidInEvent> mapToLiquidInEventList(List<FoodInfo> liquidInfoList) {
    return liquidInfoList.map((foodInfo) => LiquidInEvent(
        id: foodInfo.id!,
        qty: foodInfo.eventInfo!.qty!.toInt(),
    ),).toList();
}